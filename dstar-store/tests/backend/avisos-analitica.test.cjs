const { test, beforeEach, afterEach } = require('node:test');
const assert = require('node:assert/strict');
process.env.NODE_ENV='test';process.env.DSTAR_MEMORY_STORE='true';
process.env.PANEL_PASSWORD='test-password-long-enough';process.env.URL_SITIO='https://example.test';
const storage=require('../../netlify/lib/storage');
const stock=require('../../netlify/lib/stock-store');
const evento=require('../../netlify/handlers/evento');
const analitica=require('../../netlify/handlers/analitica');
const avisame=require('../../netlify/handlers/avisame');
const avisos=require('../../netlify/handlers/avisos');
const { clave }=require('../../netlify/lib/avisos');
const product=require('../../js/products-data').find(p=>p.sizes.length>1);
const UA='Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X)';
const realFetch=global.fetch;
let mails=[];
beforeEach(()=>{
  storage.resetForTests();mails=[];
  process.env.RESEND_API_KEY='re_test';process.env.MAIL_FROM='DSTAR <hola@example.test>';
  global.fetch=async(url,opts)=>{if(String(url).includes('resend.com')){mails.push(JSON.parse(opts.body));return {ok:true,json:async()=>({id:'m'})};}throw new Error('Unexpected network');};
});
afterEach(()=>{global.fetch=realFetch;delete process.env.RESEND_API_KEY;delete process.env.MAIL_FROM;});
const ev=(b,headers={})=>evento.handler({httpMethod:'POST',headers:{'user-agent':UA,...headers},body:JSON.stringify(b)});
const adminGet=(h,q={})=>h.handler({httpMethod:'GET',headers:{authorization:'Bearer '+process.env.PANEL_PASSWORD},queryStringParameters:q});
const adminPost=(h,b)=>h.handler({httpMethod:'POST',headers:{authorization:'Bearer '+process.env.PANEL_PASSWORD},body:JSON.stringify(b)});
const pedir=b=>avisame.handler({httpMethod:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(b)});

test('analítica agrega visitas, productos y fuentes sin datos personales',async()=>{
  await ev({e:'view',path:'/',visit:true,source:'instagram',device:'movil'});
  await ev({e:'view',path:'/producto',visit:false});
  await ev({e:'product',id:product.id});
  await ev({e:'add',id:product.id});
  await ev({e:'checkout'});
  const r=await adminGet(analitica,{dias:'7'});
  assert.equal(r.statusCode,200);
  const a=JSON.parse(r.body);
  assert.deepEqual([a.totales.visit,a.totales.view,a.totales.product,a.totales.add,a.totales.checkout],[1,2,1,1,1]);
  assert.deepEqual(a.fuentes,[['instagram',1]]);
  assert.deepEqual(a.productos,[{id:product.id,product:1,add:1}]);
  assert.equal(a.dias.length,7);
  assert.doesNotMatch(r.body,/iPhone|Mozilla/);
});
test('analítica ignora robots, eventos desconocidos y productos inexistentes',async()=>{
  await ev({e:'view',path:'/'},{'user-agent':'Googlebot/2.1'});
  await ev({e:'compra'});
  await ev({e:'product',id:'no-existe'});
  await ev({e:'view',path:'/<script>',visit:true,source:'<x>',device:'tv'});
  const a=JSON.parse((await adminGet(analitica)).body);
  assert.deepEqual(a.totales,{view:1,visit:1});
  assert.deepEqual(a.paginas,[['/otra',1]]);
  assert.deepEqual(a.fuentes,[['directo',1]]);
  assert.deepEqual(a.dispositivos,[['escritorio',1]]);
});
