test('aviso exige correo válido, consentimiento y talla existente',async()=>{
  assert.equal((await pedir({email:'mal',consent:true,tipo:'drop'})).statusCode,400);
  assert.equal((await pedir({email:'a@example.com',tipo:'drop'})).statusCode,400);
  assert.equal((await pedir({email:'a@example.com',consent:true,tipo:'talla',productId:product.id,size:'XXL-no'})).statusCode,400);
  assert.equal((await pedir({email:'a@example.com',consent:true,tipo:'drop'})).statusCode,200);
  assert.equal((await pedir({email:'A@example.com ',consent:true,tipo:'drop'})).statusCode,200);
  assert.equal((await pedir({email:'bot@example.com',consent:true,tipo:'drop',website:'spam'})).statusCode,200);
  const {avisos:lista}=JSON.parse((await adminGet(avisos)).body);
  assert.equal(lista.length,1);
  assert.equal(lista[0].email,'a@example.com');
  assert.equal(lista[0].token,undefined);
});
test('aviso de talla se envía una vez, solo con stock, y la baja funciona',async()=>{
  const size=product.sizes[0];
  await pedir({email:'a@example.com',consent:true,tipo:'talla',productId:product.id,size});
  const sinStock=await stock.leerStock({});
  if(sinStock[product.id][size]>0)await stock.ajustar({},{id:product.id,size,delta:-sinStock[product.id][size]},'vaciar','Prueba');
  assert.equal((await adminPost(avisos,{action:'notify',productId:product.id,size})).statusCode,409);
  await stock.ajustar({},{id:product.id,size,delta:2},'reponer','Prueba');
  const r=JSON.parse((await adminPost(avisos,{action:'notify',productId:product.id,size})).body);
  assert.deepEqual(r,{enviados:1,quedan:0});
  assert.equal(mails.length,1);
  assert.match(mails[0].html,/api\/avisame\?baja=talla-/);
  assert.deepEqual(JSON.parse((await adminPost(avisos,{action:'notify',productId:product.id,size})).body),{enviados:0,quedan:0});
  const id=clave({email:'a@example.com',tipo:'talla',productId:product.id,size});
  const token=(await storage.open('avisos',{}).read(id)).data.token;
  const confirmar=await avisame.handler({httpMethod:'GET',headers:{},queryStringParameters:{baja:id,t:token}});
  assert.match(confirmar.body,/CONFIRMAR BAJA/);
  const malo=await avisame.handler({httpMethod:'POST',headers:{'content-type':'application/x-www-form-urlencoded'},body:'baja='+id+'&t='+'0'.repeat(32)});
  assert.match(malo.body,/ENLACE INVÁLIDO/);
  const baja=await avisame.handler({httpMethod:'POST',headers:{'content-type':'application/x-www-form-urlencoded'},body:'baja='+id+'&t='+token});
  assert.match(baja.body,/LISTO/);
  assert.equal(JSON.parse((await adminGet(avisos)).body).avisos.length,0);
});
